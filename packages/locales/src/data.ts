import { deepAssign } from 'utilium';

/**
 * Translation data for a single locale. Keys can be nested, leaves are the translations themselves.
 */
export interface Data {
	[key: string]: string | readonly string[] | Data;
}

/** The types allowed for a replacement's value */
export type Value = string | number | bigint | boolean;

/** The plural categories of the Unicode CLDR, as used by `Intl.PluralRules` */
export const pluralCategories = ['zero', 'one', 'two', 'few', 'many', 'other'] as const;

export type PluralCategory = (typeof pluralCategories)[number];

/**
 * A translation with a form for each plural category, chosen by the `count` replacement.
 * @example { "one": "{count} file", "other": "{count} files" }
 */
export type Plural = Partial<Record<PluralCategory, string>> & { other: string };

/** Whether a value is a plural translation, which has only plural categories as keys and includes `other` */
export function isPlural(value: unknown): value is Plural {
	if (typeof value != 'object' || value === null || !('other' in value)) return false;
	return Object.entries(value).every(
		([key, form]) => pluralCategories.includes(key as PluralCategory) && typeof form == 'string'
	);
}

/**
 * Maps every known translation key to the replacements it needs.
 * Augment it with the module generated by `locales-typegen`.
 */
// eslint-disable-next-line @typescript-eslint/no-empty-object-type
export interface Keys {}

/** A translation key that is known at compile time */
export type Key = keyof Keys & string;

export const loaded: Record<string, Data> = Object.create(null);

/** Add translations to a locale. */
export function extend(locale: string, data: object): void {
	loaded[locale] ||= {};
	deepAssign(loaded[locale], data);
}

/**
 * Find the best loaded locale for a language tag, e.g. `en-US` falls back to `en`.
 */
export function resolve(tag: string): string | undefined {
	while (!(tag in loaded)) {
		if (!tag.includes('-')) return;
		tag = tag.slice(0, tag.lastIndexOf('-'));
	}
	return tag;
}

/**
 * Flatten nested translation data into `some.dotted.key` / translation pairs.
 * Arrays are flattened using their indices, e.g. `audit_severity.0`, and plural translations are kept whole.
 */
export function* flatten(data: Data, prefix: string = ''): Generator<[key: string, translation: string | Plural]> {
	for (const [key, value] of Object.entries(data)) {
		const path = prefix ? `${prefix}.${key}` : key;
		if (typeof value == 'string' || isPlural(value)) yield [path, value];
		else yield* flatten(value as Data, path);
	}
}
